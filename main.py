for epoch in range(CFG["epochs_reflection"]):
    G_refl.train(); D_refl.train()
    D_losses = []; G_losses = []

    for A, B in refl_train_dl:   # A = reflected(5ch), B = clean(3ch)
        A = A.to(device); B = B.to(device)

        # --- Train D ---
        fakeB = G_refl(A).detach()
        real_pred = D_refl(A, B)
        fake_pred = D_refl(A, fakeB)

        lossD = 0.5 * (
            F.mse_loss(real_pred, torch.ones_like(real_pred)) +
            F.mse_loss(fake_pred, torch.zeros_like(fake_pred))
        )

        optD_r.zero_grad()
        lossD.backward()
        optD_r.step()

        # --- Train G ---
        fakeB = G_refl(A)
        fake_pred = D_refl(A, fakeB)

        adv  = F.mse_loss(fake_pred, torch.ones_like(fake_pred))
        l1   = F.l1_loss(fakeB, B)
        grad = gradient_loss(fakeB, B)

        lossG = adv + 50*l1 + 5*grad

        optG_r.zero_grad()
        lossG.backward()
        optG_r.step()

        D_losses.append(lossD.item())
        G_losses.append(lossG.item())

    print(f"[Refl] Epoch {epoch+1}/{CFG['epochs_reflection']} "
          f"D={np.mean(D_losses):.4f} G={np.mean(G_losses):.4f}")

    # --- Visualization ---
    G_refl.eval()
    with torch.no_grad():
        A_s, B_s = next(iter(refl_test_dl))
        A_s, B_s = A_s.to(device), B_s.to(device)

        out = G_refl(A_s)[0]

        imgs = [
            tensor_to_image(A_s[0][:3]),  # only RGB, no mask/edges
            tensor_to_image(out),
            tensor_to_image(B_s[0]),
        ]
        show_images(imgs, ["Reflected Input", "GAN Output", "GT Clean"], cols=3)


