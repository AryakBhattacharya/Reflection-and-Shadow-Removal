print("Training on Shadows (ISTD)...")
for epoch in range(CFG["epochs_shadow"]):
    G_shadow.train(); D_shadow.train()
    lossD_epoch, lossG_epoch = [], []

    for A, B in shadow_train_dl:
        A = A.to(device)
        B = B.to(device)

        # --- Train Discriminator ---
        fakeB = G_shadow(A)
        real = D_shadow(A, B)
        fake = D_shadow(A, fakeB.detach())

        loss_D = 0.5 * (
            F.mse_loss(real, torch.ones_like(real)) +
            F.mse_loss(fake, torch.zeros_like(fake))
        )
        optD_s.zero_grad()
        loss_D.backward()
        optD_s.step()

        # --- Train Generator ---
        fakeB = G_shadow(A)
        pred_fake = D_shadow(A, fakeB)

        adv  = F.mse_loss(pred_fake, torch.ones_like(pred_fake))
        l1   = F.l1_loss(fakeB, B)
        grad = gradient_loss(fakeB, B)

        loss_G = adv + 50.0 * l1 + 5.0 * grad

        optG_s.zero_grad()
        loss_G.backward()
        optG_s.step()

        lossD_epoch.append(loss_D.item())
        lossG_epoch.append(loss_G.item())

    print(f"[Shadow] Epoch {epoch+1}/{CFG['epochs_shadow']} "
          f"D={np.mean(lossD_epoch):.4f} G={np.mean(lossG_epoch):.4f}")

    # quick visual
    G_shadow.eval()
    with torch.no_grad():
        A_s, B_s = next(iter(shadow_test_dl))
        A_s, B_s = A_s.to(device), B_s.to(device)
        out = G_shadow(A_s)[0]
