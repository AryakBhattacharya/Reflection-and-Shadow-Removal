def tensor_to_image(t):
    """
    Convert a [-1,1] normalized tensor (3×H×W) into an RGB uint8 H×W×3 image.
    """
    img = (t.detach().cpu().numpy() + 1) / 2  # [0,1]
    img = np.clip(img, 0, 1)
    img = (img * 255).astype(np.uint8)
    img = img.transpose(1, 2, 0)  # CHW -> HWC (RGB)
    return img

