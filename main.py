class ShadowDataset(Dataset):
    """
    Input  (X): 5 channels
        - RGB shadow image     (3)
        - classical shadow mask (1)
        - classical Sobel edges (1)
    Target (Y): 3-channel RGB shadow-free image
    """
    def __init__(self, triplets, img_size):
        self.triplets = triplets
        self.size = (img_size, img_size)
        self.tf = T.Compose([
            T.ToPILImage(),
            T.Resize(self.size),
            T.ToTensor(),
        ])

    def __len__(self):
        return len(self.triplets)

    def __getitem__(self, idx):
        a_path, b_path, c_path = self.triplets[idx]
        shadow_bgr = cv2.imread(a_path)
        clean_bgr  = cv2.imread(c_path)

        # classical features
        mask_u8  = classical_shadow_mask(shadow_bgr)
        edges_u8 = classical_shadow_edges(shadow_bgr)

        # RGB images
        shadow_rgb = cv2.cvtColor(shadow_bgr, cv2.COLOR_BGR2RGB)
        clean_rgb  = cv2.cvtColor(clean_bgr,  cv2.COLOR_BGR2RGB)

        shadow_t = self.tf(shadow_rgb)
        clean_t  = self.tf(clean_rgb)

        # masks to tensors
        mask_resized  = cv2.resize(mask_u8,  self.size, interpolation=cv2.INTER_NEAREST)
        edges_resized = cv2.resize(edges_u8, self.size, interpolation=cv2.INTER_NEAREST)

        mask_t  = torch.from_numpy(mask_resized / 255.0).float().unsqueeze(0)  # 1xHxW
        edges_t = torch.from_numpy(edges_resized / 255.0).float().unsqueeze(0) # 1xHxW

        inp_5ch = torch.cat([shadow_t, mask_t, edges_t], dim=0)  # 5xHxW

        # map to [-1,1]
        inp_5ch = inp_5ch * 2 - 1
        clean_t = clean_t * 2 - 1

        return inp_5ch, clean_t

