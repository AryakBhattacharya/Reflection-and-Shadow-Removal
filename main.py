        mask_t  = torch.from_numpy(cv2.resize(mask_u8, self.size) / 255.).float().unsqueeze(0)
        edges_t = torch.from_numpy(cv2.resize(edges_u8, self.size) / 255.).float().unsqueeze(0)

        refl_t  = self.tf(refl_rgb)
        clean_t = self.tf(clean_rgb)

        # Combine into 5-channel input
        inp_5ch = torch.cat([refl_t, mask_t, edges_t], dim=0)

        # Scale to [-1,1]
        return inp_5ch * 2 - 1, clean_t * 2 - 1


